import { open, save, text, sleep } from './lib.mjs';
import { spawn, execSync } from 'child_process';
const { browser, page, diag, version } = await open();
const log = [`browser ${version}`];
await page.goto('http://127.0.0.1:19871/'); await sleep(2500);
await save(page, 'qa004-0-start');
await page.click('#target-toggle');
await page.fill('#target-input', 'qa-named-proc');
await page.click('#target-save'); await sleep(8000);
await save(page, 'qa004-1-absent', 'after Monitor with absent name');
const child = spawn('/tmp/qa-6c3ba7cd/qa-named-proc', ['600'], { detached: true, stdio: 'ignore' }); child.unref();
log.push(`started pid ${child.pid} comm=${execSync(`cat /proc/${child.pid}/comm`).toString().trim()}`);
await sleep(10000);
await save(page, 'qa004-2-running', 'process started');
process.kill(child.pid);
await sleep(12000);
await save(page, 'qa004-3-stopped', 'process stopped');
await page.reload(); await sleep(3000);
await save(page, 'qa004-4-reload', 'reload after stop');
console.log(log.join('\n')); console.log('DIAG', JSON.stringify(diag));
await browser.close();
